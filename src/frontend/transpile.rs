    fn parse_and_transpile(src: &str) -> String {
        let tokens = lex(src);
        let mut parser = Parser::new(tokens);
        let stmts = parser.parse().expect("Parsing failed");
        transpile_to_js(&stmts)
    }

    #[test]
    fn test_transpile_types_erased() {
        let src = r#"
            type ID = int | string;
            let id: ID = 42;
            let name: string = "Eronom";
        "#;
        let js = parse_and_transpile(src);
        assert!(!js.contains("type ID"));
        assert!(js.contains("let id = 42;"));
        assert!(js.contains("let name = \"Eronom\";"));
    }

    #[test]
    fn test_transpile_enum() {
        let src = r#"
            enum Status {
                Pending,
                Active,
                Completed
            }
        "#;
        let js = parse_and_transpile(src);
        assert!(js.contains("const Status = Object.freeze({"));
        assert!(js.contains("Pending: 0,"));
        assert!(js.contains("Active: 1,"));
        assert!(js.contains("Completed: 2,"));
        assert!(js.contains("[0]: \"Pending\","));
    }

    #[test]
    fn test_transpile_struct_to_class() {
        let src = r#"
            struct Person {
                name: string,
                age: int,

                fn greet() {
                    return "Hello " + this.name;
                }
            }
        "#;
        let js = parse_and_transpile(src);
        assert!(js.contains("class Person {"));
        assert!(js.contains("constructor(init = {}) {"));
        assert!(js.contains("Object.assign(this, init);"));
        assert!(js.contains("greet() {"));
        assert!(js.contains("return (\"Hello \" + this.name);"));
    }

    #[test]
    fn test_transpile_typecast_and_functions() {
        let src = r#"
            fn add(a: int, b: int): int {
                return (a + b) as int;
            }
            let res = add(10, 20);
        "#;
        let js = parse_and_transpile(src);
        assert!(js.contains("function add(a, b) {"));
        assert!(js.contains("return (a + b);"));
        assert!(js.contains("let res = add(10, 20);"));
    }

