#[derive(Debug, Clone, PartialEq)]
pub enum TokenType {
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    LeftBracket,
    RightBracket,
    Comma,
    Dot,
    Minus,
    MinusMinus,
    MinusEqual,
    Plus,
    PlusPlus,
    PlusEqual,
    Colon,
    Slash,
    SlashEqual,
    Star,
    StarEqual,
    Percent,
    PercentEqual,
    Bang,
    BangEqual,
    Equal,
    EqualEqual,
    Greater,
    GreaterEqual,
    GreaterGreater,
    Less,
    LessEqual,
    LessLess,
    Ampersand,
    Pipe,
    Caret,
    Tilde,
    Question,
    Arrow,
    DotDot,
    Identifier(String),
    String(String),
    Number(f64),
    And,
    Else,
    False,
    For,
    If,
    Null,
    Or,
    Print,
    Return,
    True,
    Let,
    Const,
    In,
    Import,
    Export,
    From,
    Function,
    Struct,
    Embed,
    Interface,
    Concurrent,
    Spawn,
    On,
    While,
    Break,
    Continue,
    Try,
    Catch,
    Finally,
    Throw,
    Switch,
    Case,
    Default,
    Match,
    Typeof,
    Underscore,
    Eof,
}

#[derive(Debug, Clone)]
pub struct Token {
    pub ty: TokenType,
    pub line: usize,
    pub col: usize,
}
